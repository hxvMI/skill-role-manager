"""Seal reviewed in-repo packages. Not a tool for approving untrusted input."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def seal(root):
    plugin = json.loads((root/'plugin.json').read_text(encoding='utf-8'))
    files = {}
    for path in sorted(root.rglob('*')):
        if path.is_symlink():
            raise ValueError('Links are not permitted')
        if path.is_file() and path.name != 'manager.json':
            if '__pycache__' in path.parts or path.suffix == '.pyc':
                raise ValueError('Remove generated bytecode before sealing')
            files[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    permissions = ['local-code','write-selected-marketplace'] if plugin['name']=='skill-role-manager' else []
    contract = {'schema_version':1,'id':plugin['name'],'version':plugin['version'],
                'permissions':permissions,'dependencies':{},'files':files}
    (root/'manager.json').write_text(json.dumps(contract,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(f"Sealed {plugin['name']} {plugin['version']}: {len(files)} files")

if __name__ == '__main__':
    for path in sorted((ROOT/'plugins').iterdir()):
        if path.is_dir(): seal(path)
